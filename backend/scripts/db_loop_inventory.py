#!/usr/bin/env python3
"""Find database calls inside loops (possible N+1 queries) in backend/app.

A loop that awaits `db.get(...)` / `db.execute(...)` once per row makes one query per row. Small,
bounded write validations (a handful of voucher lines) are fine; list / report / dashboard / scan code
should batch with `IN (...)` or a join instead.

`tests/test_db_loop_budget.py` compares the result with `tests/db_loop_baseline.py` so new loops fail
review, and the baseline only shrinks.

Usage::

    docker compose exec backend python scripts/db_loop_inventory.py                 # per function
    docker compose exec backend python scripts/db_loop_inventory.py --write-baseline
"""

from __future__ import annotations

import argparse
import ast
from collections import Counter
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
APP = BACKEND / "app"
BASELINE_FILE = BACKEND / "tests" / "db_loop_baseline.py"
DB_NAMES = {"db", "session", "s"}
DB_METHODS = {"get", "execute", "scalar", "scalars"}


def _is_db_await(node: ast.AST) -> bool:
    if not isinstance(node, ast.Await) or not isinstance(node.value, ast.Call):
        return False
    func = node.value.func
    return (
        isinstance(func, ast.Attribute)
        and func.attr in DB_METHODS
        and isinstance(func.value, ast.Name)
        and func.value.id in DB_NAMES
    )


class _Finder(ast.NodeVisitor):
    def __init__(self) -> None:
        self.stack: list[str] = []
        self.found: Counter[str] = Counter()

    def _visit_func(self, node) -> None:
        self.stack.append(node.name)
        self.generic_visit(node)
        self.stack.pop()

    visit_FunctionDef = _visit_func
    visit_AsyncFunctionDef = _visit_func

    def _visit_loop(self, node) -> None:
        for child in node.body:
            for sub in ast.walk(child):
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
                    break
                if _is_db_await(sub):
                    self.found[".".join(self.stack) or "<module>"] += 1
                    break
        self.generic_visit(node)

    visit_For = _visit_loop
    visit_AsyncFor = _visit_loop
    visit_While = _visit_loop


def scan() -> dict[str, int]:
    out: dict[str, int] = {}
    for path in sorted(APP.rglob("*.py")):
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except SyntaxError:
            continue
        finder = _Finder()
        finder.visit(tree)
        rel = path.relative_to(BACKEND).as_posix()
        for func, n in finder.found.items():
            out[f"{rel}::{func}"] = n
    return out


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--write-baseline", action="store_true")
    args = p.parse_args()
    data = scan()
    if args.write_baseline:
        lines = [
            '"""Functions that still query the database inside a loop (possible N+1), with loop counts (RC-07).',
            "",
            "Generated by `python scripts/db_loop_inventory.py --write-baseline`. Only remove entries (after",
            "batching the queries or confirming the loop is a small bounded write validation).",
            '"""',
            "",
            "BASELINE: dict[str, int] = {",
        ]
        lines += [f"    {k!r}: {v}," for k, v in sorted(data.items())]
        lines += ["}", ""]
        BASELINE_FILE.write_text("\n".join(lines), encoding="utf-8")
        print(f"wrote {BASELINE_FILE} ({len(data)} functions, {sum(data.values())} loops)")
        return
    print(f"{len(data)} functions, {sum(data.values())} loops with DB calls")
    for k, v in sorted(data.items(), key=lambda kv: -kv[1])[:40]:
        print(f"  {v}  {k}")


if __name__ == "__main__":
    main()
