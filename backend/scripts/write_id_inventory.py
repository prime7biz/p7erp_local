#!/usr/bin/env python3
"""List client-supplied related-record ids on write routes (POST / PUT / PATCH under /api/v1).

Every such id must be checked to belong to the caller's tenant (`ensure_owned` / `ensure_all_owned`
or an equivalent tenant-filtered loader). `tests/test_write_id_ownership.py` keeps the reviewed list in
`tests/write_id_ownership_manifest.py` in sync with what the routes actually accept.

Usage::

    docker compose exec backend python scripts/write_id_inventory.py            # summary per module
    docker compose exec backend python scripts/write_id_inventory.py --all      # every route.field
"""

from __future__ import annotations

import argparse
import sys
import typing
from collections import Counter
from pathlib import Path

backend = Path(__file__).resolve().parent.parent
if str(backend) not in sys.path:
    sys.path.insert(0, str(backend))

# Ids that are not tenant records (pagination, external references, the caller's own context).
NOT_RELATED_RECORD_IDS = frozenset({"request_id", "idempotency_key", "client_request_id", "tenant_id", "session_id"})


def _model_id_fields(model, prefix: str = "", seen: set | None = None) -> set[str]:
    from pydantic import BaseModel

    seen = seen if seen is not None else set()
    if model in seen:
        return set()
    seen.add(model)
    out: set[str] = set()
    for name, field in getattr(model, "model_fields", {}).items():
        path = f"{prefix}{name}"
        if (name.endswith("_id") or name.endswith("_ids")) and name not in NOT_RELATED_RECORD_IDS:
            out.add(path)
        for arg in _inner_types(field.annotation):
            if isinstance(arg, type) and issubclass(arg, BaseModel):
                out |= _model_id_fields(arg, f"{path}[].", seen)
    return out


def _inner_types(annotation) -> list:
    args = list(typing.get_args(annotation)) or [annotation]
    found = []
    for a in args:
        nested = typing.get_args(a)
        found.extend(nested if nested else [a])
    return found


def write_id_fields(routes) -> dict[str, set[str]]:
    """{"METHOD /path": {"field", "items[].item_id", ...}} for write routes with id fields in the body."""
    from fastapi.routing import APIRoute

    result: dict[str, set[str]] = {}
    for route in routes:
        if not isinstance(route, APIRoute) or not route.path.startswith("/api/v1/"):
            continue
        methods = sorted(m for m in route.methods if m in {"POST", "PUT", "PATCH"})
        if not methods:
            continue
        fields: set[str] = set()
        body = route.body_field
        if body is not None:
            for arg in _inner_types(body.type_):
                fields |= _model_id_fields(arg)
        if fields:
            for m in methods:
                result[f"{m} {route.path}"] = fields
    return result


def module_of(route_key: str) -> str:
    return route_key.split(" ", 1)[1].split("/")[3]


def handler_uses_ensure_owned(routes) -> dict[str, bool]:
    """Route key -> True when the handler source calls ensure_owned / ensure_all_owned directly."""
    import inspect

    from fastapi.routing import APIRoute

    out: dict[str, bool] = {}
    for route in routes:
        if not isinstance(route, APIRoute):
            continue
        try:
            src = inspect.getsource(route.endpoint)
        except (OSError, TypeError):
            src = ""
        uses = "ensure_owned(" in src or "ensure_all_owned(" in src
        for m in route.methods:
            out[f"{m} {route.path}"] = uses
    return out


MANIFEST_FILE = backend / "tests" / "write_id_ownership_manifest.py"


HANDLER_HEURISTIC = "handler-calls-ensure_owned"


def render_manifest(routes, previous: dict[str, dict[str, str]] | None = None) -> str:
    """Manifest source. Keeps statuses from `previous`. Only the very first generation (no previous
    manifest) uses the handler-level heuristic; after that every new field starts as 'unreviewed'."""
    first_run = not previous
    previous = previous or {}
    data = write_id_fields(routes)
    uses = handler_uses_ensure_owned(routes)
    lines = [
        '"""Reviewed tenant-ownership status of every client-supplied id on write routes (RC-15).',
        "",
        "Generated by `python scripts/write_id_inventory.py --write-manifest`; keep reviewed statuses.",
        "Statuses: 'handler-calls-ensure_owned' (heuristic from the first scan: the handler calls",
        "ensure_owned somewhere; this field itself is NOT verified yet),",
        "'reviewed: <how>' (field checked by ensure_owned or a tenant-filtered loader, with a cross-tenant test),",
        "'not-a-record: <why>' (not a tenant record id), 'unreviewed' (still to check).",
        '"""',
        "",
        "MANIFEST: dict[str, dict[str, str]] = {",
    ]
    for key in sorted(data):
        lines.append(f"    {key!r}: {{")
        for f in sorted(data[key]):
            default = HANDLER_HEURISTIC if first_run and uses.get(key) else "unreviewed"
            status = previous.get(key, {}).get(f) or default
            lines.append(f"        {f!r}: {status!r},")
        lines.append("    },")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    from app.main import app

    p = argparse.ArgumentParser()
    p.add_argument("--all", action="store_true")
    p.add_argument("--write-manifest", action="store_true", help="(re)write tests/write_id_ownership_manifest.py")
    args = p.parse_args()
    data = write_id_fields(app.routes)
    if args.write_manifest:
        previous: dict[str, dict[str, str]] = {}
        if MANIFEST_FILE.exists():
            scope: dict = {}
            exec(MANIFEST_FILE.read_text(encoding="utf-8"), scope)  # noqa: S102 - our own generated file
            previous = scope.get("MANIFEST", {})
        MANIFEST_FILE.write_text(render_manifest(app.routes, previous), encoding="utf-8")
        print(f"wrote {MANIFEST_FILE}")
        return
    if args.all:
        for key in sorted(data):
            for f in sorted(data[key]):
                print(f"{key}  {f}")
        return
    per_module = Counter()
    for key, fields in data.items():
        per_module[module_of(key)] += len(fields)
    total = sum(per_module.values())
    print(f"write routes with related ids: {len(data)}; id fields: {total}")
    for mod, n in per_module.most_common():
        print(f"  {mod}: {n}")


if __name__ == "__main__":
    main()
