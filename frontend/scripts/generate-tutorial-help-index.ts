/**
 * Writes src/data/tutorials/helpIndex.generated.ts: id, title, summary and related routes of every
 * tutorial article. The header Help button loads only this small file, not the whole library.
 *
 * Run after editing tutorial sections:  npm run generate:help-index
 * (also runs in `npm run prebuild`; `helpIndex.test.ts` fails when the file is out of date)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { toHelpEntries } from "../src/data/tutorials/helpIndex.ts";
import { tutorialSections } from "../src/data/tutorials/tutorialSections.ts";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_FILE = path.join(__dirname, "..", "src", "data", "tutorials", "helpIndex.generated.ts");

export function renderHelpIndex(): string {
  const entries = toHelpEntries(tutorialSections.flatMap((s) => s.articles));
  return [
    "// Generated by scripts/generate-tutorial-help-index.ts. Do not edit; run `npm run generate:help-index`.",
    'import type { TutorialHelpEntry } from "./helpIndex";',
    "",
    `export const tutorialHelpIndex: TutorialHelpEntry[] = ${JSON.stringify(entries, null, 2)};`,
    "",
  ].join("\n");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  fs.writeFileSync(OUT_FILE, renderHelpIndex(), "utf8");
  console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)}`);
}
